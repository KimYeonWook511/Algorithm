select item_id, item_name, rarity
  from item_info as ii
  where exists (select 1
                  from item_info as i
                  join item_tree as t
                    on i.item_id = t.parent_item_id
                  where i.rarity = 'RARE'
                    and ii.item_id = t.item_id)
  order by item_id desc;